import {readFile,writeFile} from 'node:fs/promises';
const {questions}=JSON.parse(await readFile('public/arcade/bank.json','utf8'));
if(!questions.length||JSON.stringify(questions).includes('$arcade$'))throw Error('Invalid arcade question catalog');
const commands=['-- Generated by scripts/seed-arcade-bank.mjs after 014_arcade_rooms.sql.','begin;'];
for(let i=0;i<questions.length;i+=60){
 const data=JSON.stringify(questions.slice(i,i+60));
 commands.push(`insert into school_private.arcade_bank(id,lesson,level,question)
select q->>'id',q->>'lesson',q->>'level',q from jsonb_array_elements($arcade$${data}$arcade$::jsonb) q
on conflict(id) do update set lesson=excluded.lesson,level=excluded.level,question=excluded.question;`);
}
await writeFile('supabase/migrations/015_arcade_bank.sql',[...commands,'commit;',''].join('\n'));
