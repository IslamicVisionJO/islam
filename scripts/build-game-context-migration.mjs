import {readFile,writeFile} from 'node:fs/promises';
import vm from 'node:vm';

const root=new URL('../',import.meta.url);
const read=file=>readFile(new URL(file,root),'utf8');
const accepts=vm.runInNewContext(await read('src/core.js')+'\n;isStandaloneGameQuestion');
const classic=JSON.parse((await read('supabase/migrations/004_online_duels.sql')).match(/\$duel_seed\$([\s\S]*?)\$duel_seed\$/)[1]);
const games=JSON.parse((await read('supabase/migrations/005_educational_online.sql')).match(/\$edu_seed\$([\s\S]*?)\$edu_seed\$/)[1]);
const classicIds=classic.filter(q=>!accepts({prompt:q.prompt,payload:{options:q.options}})).map(q=>q.id);
const gameIds=games.filter(row=>!accepts(row.data)).map(({game,id})=>({game,id}));
const sql=`-- Generated by scripts/build-game-context-migration.mjs from the official seed files.
-- Move context-dependent seeds out of new draws; existing rooms retain their question snapshots.
begin;
create table if not exists school_private.game_context_archive (
 kind text not null check(kind in ('duel','educational')),
 id text not null,
 game int not null,
 payload jsonb not null,
 primary key(kind,id,game)
);
alter table school_private.game_context_archive enable row level security;
revoke all on school_private.game_context_archive from public,anon,authenticated;

with moved as (
 delete from school_private.duel_questions q
 using jsonb_array_elements_text($classic$${JSON.stringify(classicIds)}$classic$::jsonb) d(id)
 where q.id=d.id
 returning q.id,q.question
)
insert into school_private.game_context_archive(kind,id,game,payload)
select 'duel',id,-1,question from moved on conflict do nothing;

with moved as (
 delete from school_private.educational_questions q
 using jsonb_to_recordset($educational$${JSON.stringify(gameIds)}$educational$::jsonb) d(game int,id text)
 where q.game=d.game and q.id=d.id
 returning q.*
)
insert into school_private.game_context_archive(kind,id,game,payload)
select 'educational',m.id,m.game,to_jsonb(m) from moved m on conflict do nothing;
commit;
`;
await writeFile(new URL('supabase/migrations/010_standalone_game_questions.sql',root),sql);
console.log('Context-dependent seed rows:',classicIds.length,'classic and',gameIds.length,'educational.');
